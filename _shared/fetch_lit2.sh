#!/bin/bash
# 下载综述要引用的论文原文到 _lit2，已存在则跳过
cd "$(dirname "$0")/../_lit2" || exit 1
export NO_PROXY='*'
for id in 2402.03300 2503.20783 2404.10719 2504.13837 2506.14245 2212.08073 2309.00267 2310.12036 2402.01306 2403.07691 2305.20050 2507.18071 2504.16084 2506.18254 2409.19256 2405.11143 2312.08935 2502.01456 2210.10760 2401.10020 2402.04792 2305.11206; do
  [ -s "$id.pdf" ] && continue
  curl -sL --max-time 120 -o "$id.pdf" "https://arxiv.org/pdf/$id" ; echo "$id $(stat -c %s $id.pdf 2>/dev/null) $(head -c 5 $id.pdf)"
done
